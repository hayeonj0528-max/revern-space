export const REFLECTION_INTERVAL_SEC = 48;

/** Deterministic shuffle for a session seed. */
export function shuffleReflectionOrder(seed: number): number[] {
  const order = REFLECTION_QUESTIONS.map((_, i) => i);
  let s = seed >>> 0 || 1;
  for (let i = order.length - 1; i > 0; i--) {
    s = (s * 1664525 + 1013904223) >>> 0;
    const j = s % (i + 1);
    const tmp = order[i]!;
    order[i] = order[j]!;
    order[j] = tmp;
  }
  return order;
}
